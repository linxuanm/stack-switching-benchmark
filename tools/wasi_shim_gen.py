#!/usr/bin/env python3
"""Generate a minimal wasi_snapshot_preview1 shim (.wat) for the Wasm reference
interpreter.

The reference interpreter only provides the `spectest` and `env` host modules,
so a wasm_of_ocaml module compiled with `--enable wasi` cannot be instantiated
on its own. This shim implements the handful of WASI calls such a module
imports. It is meant to be merged into the main module with binaryen's
`wasm-merge`, which fuses it onto the main module's exported memory:

    wasm-merge main.wasm "main" shim.wasm "wasi_snapshot_preview1" -o merged.wasm

stdout/stderr bytes are emitted one per line via `spectest.print_i32`, which the
reference interpreter does provide.
"""
import argparse, sys


def gen(argv):
    blobs, ptrs, off = [], [], 0
    for a in argv:
        b = a.encode() + b"\0"
        ptrs.append(off)
        blobs.append(b)
        off += len(b)
    total = off
    argc = len(argv)

    w = []
    w.append(";; Generated by tools/wasi_shim_gen.py -- do not edit by hand.")
    w.append(";; argv = %r" % (argv,))
    w.append("(module")
    w.append('  (import "main" "memory" (memory 0))')
    w.append('  (import "spectest" "print_i32" (func $print_i32 (param i32)))')
    w.append("")
    w.append("  ;; fd_write(fd, iovs, iovs_len, nwritten) -> errno")
    w.append('  (func (export "fd_write")')
    w.append("    (param $fd i32) (param $iovs i32) (param $iovs_len i32) (param $nwritten i32)")
    w.append("    (result i32)")
    w.append("    (local $i i32) (local $total i32) (local $ptr i32) (local $len i32) (local $j i32)")
    w.append("    (block $done")
    w.append("      (loop $iov")
    w.append("        (br_if $done (i32.ge_u (local.get $i) (local.get $iovs_len)))")
    w.append("        (local.set $ptr (i32.load (i32.add (local.get $iovs) (i32.mul (local.get $i) (i32.const 8)))))")
    w.append("        (local.set $len (i32.load offset=4 (i32.add (local.get $iovs) (i32.mul (local.get $i) (i32.const 8)))))")
    w.append("        (local.set $j (i32.const 0))")
    w.append("        (block $bdone")
    w.append("          (loop $b")
    w.append("            (br_if $bdone (i32.ge_u (local.get $j) (local.get $len)))")
    w.append("            (call $print_i32 (i32.load8_u (i32.add (local.get $ptr) (local.get $j))))")
    w.append("            (local.set $j (i32.add (local.get $j) (i32.const 1)))")
    w.append("            (br $b)))")
    w.append("        (local.set $total (i32.add (local.get $total) (local.get $len)))")
    w.append("        (local.set $i (i32.add (local.get $i) (i32.const 1)))")
    w.append("        (br $iov)))")
    w.append("    (i32.store (local.get $nwritten) (local.get $total))")
    w.append("    (i32.const 0))")
    w.append("")
    w.append("  ;; args_sizes_get(argc_ptr, argv_buf_size_ptr) -> errno")
    w.append('  (func (export "args_sizes_get") (param $argc i32) (param $bufsz i32) (result i32)')
    w.append("    (i32.store (local.get $argc) (i32.const %d))" % argc)
    w.append("    (i32.store (local.get $bufsz) (i32.const %d))" % total)
    w.append("    (i32.const 0))")
    w.append("")
    w.append("  ;; args_get(argv, argv_buf) -> errno")
    w.append('  (func (export "args_get") (param $argv i32) (param $buf i32) (result i32)')
    for i, p in enumerate(ptrs):
        w.append("    (i32.store offset=%d (local.get $argv) (i32.add (local.get $buf) (i32.const %d)))" % (4 * i, p))
    pos = 0
    for b in blobs:
        for byte in b:
            w.append("    (i32.store8 offset=%d (local.get $buf) (i32.const %d))" % (pos, byte))
            pos += 1
    w.append("    (i32.const 0))")
    w.append("")
    w.append("  ;; random_get(buf, len) -> errno ; deterministic zero fill")
    w.append('  (func (export "random_get") (param $buf i32) (param $len i32) (result i32)')
    w.append("    (local $i i32)")
    w.append("    (block $done")
    w.append("      (loop $l")
    w.append("        (br_if $done (i32.ge_u (local.get $i) (local.get $len)))")
    w.append("        (i32.store8 (i32.add (local.get $buf) (local.get $i)) (i32.const 0))")
    w.append("        (local.set $i (i32.add (local.get $i) (i32.const 1)))")
    w.append("        (br $l)))")
    w.append("    (i32.const 0))")
    w.append("")
    w.append("  ;; ---- clock ----")
    w.append("  ;; A monotonic virtual clock: every query advances by 1ms. The reference")
    w.append("  ;; interpreter has no real clock, and a deterministic one keeps runs")
    w.append("  ;; reproducible. Timings printed by a benchmark are therefore virtual.")
    w.append("  (global $clock (mut i64) (i64.const 0))")
    w.append('  (func (export "clock_time_get") (param $id i32) (param $prec i64) (param $out i32) (result i32)')
    w.append("    (global.set $clock (i64.add (global.get $clock) (i64.const 1000000)))")
    w.append("    (i64.store (local.get $out) (global.get $clock))")
    w.append("    (i32.const 0))")
    w.append('  (func (export "clock_res_get") (param $id i32) (param $out i32) (result i32)')
    w.append("    (i64.store (local.get $out) (i64.const 1000))")
    w.append("    (i32.const 0))")
    w.append("")
    w.append("  ;; ---- environment ----")
    w.append('  (func (export "environ_sizes_get") (param $c i32) (param $s i32) (result i32)')
    w.append("    (i32.store (local.get $c) (i32.const 0))")
    w.append("    (i32.store (local.get $s) (i32.const 0))")
    w.append("    (i32.const 0))")
    w.append('  (func (export "environ_get") (param i32) (param i32) (result i32) (i32.const 0))')
    w.append("")
    w.append("  ;; ---- file descriptors: just enough to keep stdio alive ----")
    w.append("  ;; fd_seek -> ESPIPE (29): stdout is a pipe, not seekable")
    w.append('  (func (export "fd_seek") (param i32) (param i64) (param i32) (param i32) (result i32)')
    w.append("    (i32.const 29))")
    w.append('  (func (export "fd_close") (param i32) (result i32) (i32.const 0))')
    w.append('  (func (export "fd_sync") (param i32) (result i32) (i32.const 0))')
    w.append('  (func (export "fd_datasync") (param i32) (result i32) (i32.const 0))')
    w.append("  ;; fd_read -> report EOF")
    w.append('  (func (export "fd_read") (param i32) (param i32) (param i32) (param $nread i32) (result i32)')
    w.append("    (i32.store (local.get $nread) (i32.const 0))")
    w.append("    (i32.const 0))")
    w.append("  ;; fd_fdstat_get: zero the 24-byte fdstat, claim a character device")
    w.append('  (func (export "fd_fdstat_get") (param $fd i32) (param $buf i32) (result i32)')
    w.append("    (i64.store offset=0 (local.get $buf) (i64.const 0))")
    w.append("    (i64.store offset=8 (local.get $buf) (i64.const 0))")
    w.append("    (i64.store offset=16 (local.get $buf) (i64.const 0))")
    w.append("    (i32.store8 (local.get $buf) (i32.const 2))  ;; filetype = character_device")
    w.append("    (i32.const 0))")
    w.append('  (func (export "fd_fdstat_set_flags") (param i32) (param i32) (result i32) (i32.const 0))')
    w.append("  ;; EBADF (8) -- no preopened directories, so no filesystem")
    w.append('  (func (export "fd_prestat_get") (param i32) (param i32) (result i32) (i32.const 8))')
    w.append('  (func (export "fd_prestat_dir_name") (param i32) (param i32) (param i32) (result i32) (i32.const 8))')
    w.append('  (func (export "fd_filestat_get") (param i32) (param i32) (result i32) (i32.const 8))')
    w.append("")
    w.append("  ;; ---- filesystem: absent ----")
    w.append("  ;; ENOENT (44)")
    w.append('  (func (export "path_open")')
    w.append("    (param i32) (param i32) (param i32) (param i32) (param i32)")
    w.append("    (param i64) (param i64) (param i32) (param i32) (result i32)")
    w.append("    (i32.const 44))")
    w.append('  (func (export "path_filestat_get") (param i32) (param i32) (param i32) (param i32) (param i32) (result i32)')
    w.append("    (i32.const 44))")
    w.append('  (func (export "path_unlink_file") (param i32) (param i32) (param i32) (result i32) (i32.const 44))')
    w.append("")
    w.append("  ;; ---- scheduling ----")
    w.append('  (func (export "sched_yield") (result i32) (i32.const 0))')
    w.append("  ;; ENOTSUP (58)")
    w.append('  (func (export "poll_oneoff") (param i32) (param i32) (param i32) (param i32) (result i32)')
    w.append("    (i32.const 58))")
    w.append("")
    w.append("  ;; proc_exit returns so the interpreter finishes cleanly instead of trapping")
    w.append('  (func (export "proc_exit") (param i32))')
    w.append(")")
    return "\n".join(w) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-o", "--output", default="-", help="output .wat (default stdout)")
    ap.add_argument("argv", nargs="*", help="argv to expose to the guest (argv[0] first)")
    a = ap.parse_args()
    argv = a.argv if a.argv else ["prog"]
    text = gen(argv)
    if a.output == "-":
        sys.stdout.write(text)
    else:
        open(a.output, "w").write(text)


if __name__ == "__main__":
    main()
